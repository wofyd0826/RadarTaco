"""nuScenes radar-camera-depth dataset.

Expects preprocessed structure under `data_root`:
    radar/scene_XXXX/{cam_filename}.npy            [N, 7]  (x, y, depth, rcs, vx, vy, _)
    depth_lidar/scene_XXXX/{cam_filename}.png      uint16 (× 256)  sparse single-frame LiDAR
    depth_interp/scene_XXXX/{cam_filename}.png     uint16 (× 256)  Delaunay-interp dense GT
    depth_acc/scene_XXXX/{cam_filename}.png        uint16 (× 256)  paper-faithful 80+80 accumulated GT
    splits/{train,val,test,val_day,val_night}.txt  tab-sep "sample_id\\tabs_image_path"

`is_night` is determined per-sample from a `night_ids.txt` file (one
sample_id per line) generated by `scripts/make_splits.py`. If the file is
missing, all samples default to `is_night=False`.
"""
import os
from typing import Dict, Optional, Set

import numpy as np
import torch
from PIL import Image, ImageFile

from .base import BaseRadarDepthDataset
from .intrinsics import NUSCENES_CAM_FRONT_INTRINSIC, expand_to_6ch

# A handful of preprocessed depth_interp PNGs are slightly truncated; PIL
# raises OSError on .load() unless this flag is set. Enabling it makes the
# loader robust without skipping samples.
ImageFile.LOAD_TRUNCATED_IMAGES = True


class NuScenesRadarDepthDataset(BaseRadarDepthDataset):

    def __init__(
        self,
        data_root: str,
        split_file: str,
        dense_gt_dir: str = "depth_acc",
        lidar_gt_dir: str = "depth_lidar",
        radar_3d_dir: str = "radar_3d",
        night_ids_file: Optional[str] = None,
        rel_depth_dir: Optional[str] = None,
        **kwargs,
    ):
        """
        Args:
            lidar_gt_dir: subdir under data_root for the sparse LiDAR
                supervision target (depth_gt_lidar). Default "depth_lidar"
                = raw single-frame projection. Set to "depth_lidar_filled"
                to use the residual-fill variant.
            dense_gt_dir: subdir under data_root for dense GT (`Dacc` source).
                "depth_acc"    = paper-faithful sparse 80+80 accumulated (default).
                "depth_interp" = Delaunay-interpolated dense (alternative).
            radar_3d_dir: subdir under data_root holding sidecar (N, 3)
                ego-frame (front, left, up) coords matching the existing
                `radar/` npy line-by-line. Generated by
                `scripts/preprocess_radar_3d.py`. If a sidecar file is
                missing (e.g. preprocessing not yet run), the loader falls
                back to inverse-projecting from (x_pix, y_pix, depth) using
                the constant CAM_FRONT intrinsic — slightly less accurate
                near the image edges but architecturally identical.
            night_ids_file: optional path to a text file listing night
                sample_ids (one per line). Used to set per-sample `is_night`.
        """
        super().__init__(**kwargs)
        self.data_root = data_root
        self.dense_gt_dir = dense_gt_dir
        self.lidar_gt_dir = lidar_gt_dir
        self.radar_3d_dir = radar_3d_dir
        self.rel_depth_dir = rel_depth_dir
        self.samples = self._load_split(split_file)
        self.night_ids: Set[str] = self._load_night_ids(night_ids_file)
        self._radar3d_missing_warned = False

    # ----------------------------------------------------------- loading --
    @staticmethod
    def _load_split(split_file: str):
        if split_file.endswith(".pkl"):
            import pickle
            with open(split_file, "rb") as f:
                ids = pickle.load(f)
            return [{"sample_id": sid, "image_path": None} for sid in ids]
        out = []
        with open(split_file) as f:
            for line in f:
                line = line.strip()
                if not line:
                    continue
                parts = line.split("\t")
                out.append({
                    "sample_id": parts[0],
                    "image_path": parts[1] if len(parts) > 1 else None,
                })
        return out

    @staticmethod
    def _load_night_ids(path: Optional[str]) -> Set[str]:
        if path is None or not os.path.exists(path):
            return set()
        with open(path) as f:
            return {line.strip() for line in f if line.strip()}

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int) -> Dict:
        entry = self.samples[idx]
        sample_id = entry["sample_id"]
        image_path = entry["image_path"]
        sub = sample_id

        rgb = np.asarray(Image.open(image_path).convert("RGB"))
        rgb_norm = self._normalize_rgb(rgb)

        radar_path = os.path.join(self.data_root, "radar", f"{sub}.npy")
        radar_raw = np.load(radar_path)
        if len(radar_raw) == 0:
            radar_points = np.zeros((0, 6), dtype=np.float32)
        else:
            pts3 = radar_raw[:, :3].astype(np.float32)
            # Try to load the sidecar (N, 3) ego-frame coords produced by
            # `scripts/preprocess_radar_3d.py` (precise, derived from raw
            # PCDs through the official nuScenes calibration chain).
            radar3d_path = os.path.join(self.data_root, self.radar_3d_dir, f"{sub}.npy")
            if os.path.exists(radar3d_path):
                ego = np.load(radar3d_path).astype(np.float32)        # (N, 3)
                if ego.shape[0] != pts3.shape[0]:
                    raise RuntimeError(
                        f"sidecar 3D length {ego.shape[0]} ≠ radar npy "
                        f"length {pts3.shape[0]} for {sub}; preprocessing "
                        f"may be stale — re-run preprocess_radar_3d.py")
                radar_points = np.concatenate([ego, pts3], axis=-1)    # (N, 6)
            else:
                # Fallback: inverse-project using the constant CAM_FRONT
                # intrinsic. Off by a constant origin offset (camera
                # mounting) which is fine for kNN — distances are
                # translation-invariant — but `front`/`left`/`up` will not
                # be exactly the raw radar PCD coords until preprocessing
                # is run.
                if not self._radar3d_missing_warned:
                    import warnings
                    warnings.warn(
                        f"radar_3d sidecar missing at {radar3d_path}. "
                        f"Falling back to inverse-projection. Run "
                        f"`python scripts/preprocess_radar_3d.py` to "
                        f"populate the precise PCD-derived coords.",
                        stacklevel=2)
                    self._radar3d_missing_warned = True
                radar_points = expand_to_6ch(pts3, NUSCENES_CAM_FRONT_INTRINSIC)
        radar_points_t, radar_mask = self._pad_radar_points(radar_points)

        # Sparse LiDAR depth (or residual-filled variant when configured)
        d_lidar_path = os.path.join(self.data_root, self.lidar_gt_dir, f"{sub}.png")
        d_lidar = np.asarray(Image.open(d_lidar_path), dtype=np.float32) / 256.0
        depth_gt_lidar, valid_mask_lidar = self._make_depth_tensor(d_lidar)

        # Dense / accumulated GT (fall back to lidar if missing — e.g., test split)
        dense_path = os.path.join(self.data_root, self.dense_gt_dir, f"{sub}.png")
        if os.path.exists(dense_path):
            d_dense = np.asarray(Image.open(dense_path), dtype=np.float32) / 256.0
            depth_gt_dense, valid_mask_dense = self._make_depth_tensor(d_dense)
        else:
            depth_gt_dense = depth_gt_lidar.clone()
            valid_mask_dense = valid_mask_lidar.clone()

        H, W = depth_gt_lidar.shape[-2], depth_gt_lidar.shape[-1]
        rel_depth_path = None
        if self.rel_depth_dir is not None:
            rel_depth_path = os.path.join(self.data_root, self.rel_depth_dir, f"{sub}.png")
        rel_depth = self._load_rel_depth(rel_depth_path, (H, W))

        sample = {
            "rgb_norm": rgb_norm,
            "radar_points": radar_points_t,
            "radar_mask": radar_mask,
            "depth_gt_lidar": depth_gt_lidar,
            "depth_gt_dense": depth_gt_dense,
            "valid_mask_lidar": valid_mask_lidar,
            "valid_mask_dense": valid_mask_dense,
            "rel_depth": rel_depth,
            "is_night": torch.tensor(sample_id in self.night_ids, dtype=torch.bool),
            "is_sim": torch.tensor(False, dtype=torch.bool),
            "sample_id": sample_id,
        }
        sample = self._apply_resize(sample)
        sample = self._apply_random_crop(sample)
        sample = self._apply_augmentation(sample)
        return sample
